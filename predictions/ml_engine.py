BASE_DIR = Path(__file__).resolve().parent.parent
ML_ASSETS_DIR = BASE_DIR / 'ml_assets'
ML_ASSETS_DIR.mkdir(parents=True, exist_ok=True)


class DiseaseRiskModel:
    def __init__(self, disease_key, name, features_spec, intercept, coefficients, base_risk=0.15):
        self.disease_key = disease_key
        self.name = name
        self.features_spec = features_spec  # list of dicts: {name, label, unit, mean, std, weight, desc}
        self.intercept = intercept
        self.coefficients = coefficients
        self.base_risk = base_risk
        self.model_version = f"MediPredict-{disease_key.capitalize()}-v1.2"

    def predict(self, input_dict):
        """
        Takes raw validated input dict, standardizes features,
        calculates calibrated risk probability and feature contributions.
        """
        z = self.intercept
        contributions = []

        for spec in self.features_spec:
            fname = spec['name']
            val = float(input_dict.get(fname, spec['mean']))
            mean = spec['mean']
            std = spec['std'] if spec['std'] > 0 else 1.0
            coef = self.coefficients.get(fname, 0.0)

            # Standardized z-score
            z_score = (val - mean) / std
            feature_impact = z_score * coef
            z += feature_impact

            # Classify impact direction
            impact_type = 'Neutral'
            if feature_impact > 0.15:
                impact_type = 'Increases Risk'
            elif feature_impact < -0.15:
                impact_type = 'Lowers Risk'

            contributions.append({
                'feature': fname,
                'label': spec['label'],
                'value': val,
                'unit': spec['unit'],
                'healthy_baseline': spec['mean'],
                'impact_score': round(float(feature_impact), 3),
                'impact_type': impact_type,
                'importance_pct': round(abs(float(coef)) * 10, 1),
                'clinical_context': spec['desc']
            })

        # Sigmoid calibration
        probability = 1.0 / (1.0 + math.exp(-max(min(z, 12.0), -12.0)))
        risk_pct = round(probability * 100.0, 1)

        # Risk Tier
        if risk_pct < 30.0:
            risk_level = 'Low'
            risk_label = f'Low Estimated Risk ({risk_pct}%)'
            color = '#10b981' # Green
            badge_class = 'bg-success'
        elif risk_pct < 65.0:
            risk_level = 'Moderate'
            risk_label = f'Moderate Estimated Risk ({risk_pct}%)'
            color = '#f59e0b' # Amber
            badge_class = 'bg-warning text-dark'
        else:
            risk_level = 'High'
            risk_label = f'High Estimated Risk ({risk_pct}%)'
            color = '#ef4444' # Red
            badge_class = 'bg-danger'

        # Sort contributions by absolute impact
        contributions.sort(key=lambda x: abs(x['impact_score']), reverse=True)

        return {
            'disease_key': self.disease_key,
            'disease_name': self.name,
            'risk_score': risk_pct,
            'risk_level': risk_level,
            'risk_label': risk_label,
            'color': color,
            'badge_class': badge_class,
            'model_version': self.model_version,
            'top_contributors': contributions[:5],
            'all_contributors': contributions,
            'disclaimer': (
                "IMPORTANT MEDICAL NOTICE: This risk assessment is generated by an artificial "
                "intelligence model for informational and screening awareness only. It does NOT "
                "constitute a clinical diagnosis, medical evaluation, or treatment recommendation. "
                "Consult a licensed physician for professional medical diagnosis and care."
            )
        }


