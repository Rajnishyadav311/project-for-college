class ModelRegistry:
    def __init__(self):
        self.models = {
            'diabetes': DiseaseRiskModel('diabetes', 'Type 2 Diabetes Mellitus', DIABETES_SPECS, intercept=-1.8, coefficients=DIABETES_COEFS),
            'heart': DiseaseRiskModel('heart', 'Cardiovascular & Coronary Heart Disease', HEART_SPECS, intercept=-1.6, coefficients=HEART_COEFS),
            'kidney': DiseaseRiskModel('kidney', 'Chronic Kidney Disease (CKD)', KIDNEY_SPECS, intercept=-1.9, coefficients=KIDNEY_COEFS),
        }
        self._ensure_artifacts_saved()

    def _ensure_artifacts_saved(self):
        for key, model in self.models.items():
            joblib_path = ML_ASSETS_DIR / f"{key}_model.joblib"
            try:
                bundle = {
                    'name': model.name,
                    'key': model.disease_key,
                    'version': model.model_version,
                    'features': [s['name'] for s in model.features_spec],
                    'specs': model.features_spec,
                    'intercept': model.intercept,
                    'coefficients': model.coefficients,
                    'is_verified': True,
                }
                joblib.dump(bundle, joblib_path)
            except Exception as e:
                pass

    def get_model(self, disease_key):
        return self.models.get(disease_key)


# Global registry singleton
registry = ModelRegistry()

def predict_disease_risk(disease_type, input_dict):
    model = registry.get_model(disease_type)
    if not model:
        raise ValueError(f"Unknown disease prediction module: {disease_type}")
    return model.predict(input_dict)
