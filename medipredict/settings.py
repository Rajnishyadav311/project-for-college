# Database Configuration with MySQL and Graceful Fallback
def is_mysql_available(host='127.0.0.1', port=3306):
    try:
        sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        sock.settimeout(0.5)
        result = sock.connect_ex((host, port))
        sock.close()
        return result == 0
    except Exception:
        return False

USE_MYSQL = os.environ.get('USE_MYSQL', '').lower() in ('1', 'true') or is_mysql_available()

